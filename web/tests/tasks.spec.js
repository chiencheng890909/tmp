test('對象 按 Tab 收成標籤、維持焦點、可刪除並保留前導零', async ({ page }) => {
  await openTasks(page)
  await expect(page.locator('.task-form input[required]')).toHaveCount(1)
  const target = page.getByLabel('對象', { exact: true })
  await target.fill('00123')
  await target.press('Tab')
  await expect(page.locator('.target-tag')).toHaveCount(1)
  await expect(page.locator('.target-tag').first()).toContainText('00123')
  await expect(target).toBeFocused()
  await expect(target).toHaveValue('')
  await target.fill('00456')
  await target.press('Tab')
  await expect(page.locator('.target-tag')).toHaveCount(2)
  await expect(target).toBeFocused()
  await target.press('Tab')
  await expect(target).not.toBeFocused()
  await page.getByRole('button', { name: '移除第 1 筆 對象 00123', exact: true }).click()
  await expect(page.locator('.target-tag')).toHaveCount(1)
  await expect(page.locator('.target-tag')).toContainText('00456')
  await target.fill('ABC')
  await target.press('Tab')
  await expect(page.getByRole('alert')).toContainText(copy.tasks.targetError)
  await expect(page.locator('.target-tag')).toHaveCount(1)
  await target.fill('00999')
  await target.press('Enter')
  await expect(page.locator('.target-tag')).toHaveCount(2)
  await expect(page.locator('.task-state')).toHaveText(copy.tasks.idle)
  expect(parseTargets('00123\t 00456')).toEqual(['00123', '00456'])
  expect(() => parseTargets('00123\t\t00456')).toThrow()
})

