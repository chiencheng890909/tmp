test('真實接口的建立、輪詢、錯誤重試與結果呈現', async ({ page }) => {
  let starts = 0, polls = 0
  const output = demoReview(); output.deck.title = 'Server task result'
  await page.route('**/app-config.json', route => route.fulfill({ json: { reviewEndpoint: null, taskEndpoint: '/api/tasks' } }))
  await page.route('**/api/tasks', route => {
    starts++
    expect(route.request().method()).toBe('POST')
    expect(route.request().headers()['content-type']).toContain('application/json')
    expect(route.request().postDataJSON()).toEqual({ skillId: 'adapt-presentation', presentationId: 'server-presentation-42', inputs: { target: '00123\t00456' } })
    return starts === 1 ? route.fulfill({ status: 503 }) : route.fulfill({ json: { id: 'task-1' } })
  })
  await page.route('**/api/tasks/presentations', route => route.fulfill({ json: { presentations: [{ id: 'server-presentation-42', title: 'Server deck', author: 'Server author', slideCount: 3 }] } }))
  await page.route('**/api/tasks/task-1', route => {
    polls++
    return route.fulfill({ json: polls === 1 ? { status: 'running', progress: 45, stageIndex: 1, message: 'Processing on server' } : { status: 'completed', progress: 100, result: output } })
  })
  await openTasks(page)
  await fill(page)
  await page.getByRole('button', { name: copy.tasks.start, exact: true }).click()
  await expect(page.locator('.task-state')).toHaveText(copy.tasks.failed)
  await page.getByRole('button', { name: copy.tasks.retry, exact: true }).click()
  await expect(page.getByRole('region', { name: copy.tasks.resultTitle })).toBeVisible({ timeout: 10000 })
  await expect(page.locator('.task-log')).toContainText('Processing on server')
  expect(starts).toBe(2); expect(polls).toBe(2)
})

